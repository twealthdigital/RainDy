package com.example.util

import android.content.Context
import android.content.Intent
import android.provider.CalendarContract
import java.util.Calendar

object CalendarHelper {

    fun addWeatherEventToCalendar(
        context: Context,
        title: String,
        description: String,
        location: String,
        startHourOffset: Int = 1,
        durationHours: Int = 2
    ): Boolean {
        return try {
            val calStart = Calendar.getInstance().apply {
                add(Calendar.HOUR_OF_DAY, startHourOffset)
                set(Calendar.MINUTE, 0)
                set(Calendar.SECOND, 0)
            }
            val calEnd = Calendar.getInstance().apply {
                timeInMillis = calStart.timeInMillis
                add(Calendar.HOUR_OF_DAY, durationHours)
            }

            val intent = Intent(Intent.ACTION_INSERT).apply {
                data = CalendarContract.Events.CONTENT_URI
                putExtra(CalendarContract.Events.TITLE, "[RainDy] $title")
                putExtra(CalendarContract.Events.DESCRIPTION, "$description\n\nGenerated by RainDy Climate Smart Scheduler.")
                putExtra(CalendarContract.Events.EVENT_LOCATION, location)
                putExtra(CalendarContract.EXTRA_EVENT_BEGIN_TIME, calStart.timeInMillis)
                putExtra(CalendarContract.EXTRA_EVENT_END_TIME, calEnd.timeInMillis)
                putExtra(CalendarContract.Events.ACCESS_LEVEL, CalendarContract.Events.ACCESS_PUBLIC)
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }

            context.startActivity(intent)
            true
        } catch (e: Exception) {
            false
        }
    }
}
